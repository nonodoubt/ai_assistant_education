_AGE_PATTERNS = [
    r'(\d{1,2})\s*-?\s*лет',       # 5 лет, 5-летней, 5-летнего
    r'(\d{1,2})\s*-?\s*год',        # 3 года, 3-годовалый
    r'ребёнку\s*(\d{1,2})',
    r'ребенку\s*(\d{1,2})',
    r'дочке?\s*(\d{1,2})',
    r'дочери\s*(\d{1,2})',
    r'сыну\s*(\d{1,2})',
    r'мальчик\w*\s+(\d{1,2})',
    r'девочк\w*\s+(\d{1,2})',
    r'дочк\w*\s+(\d{1,2})',
    r'сын\w*\s+(\d{1,2})',
    r'ребёнок\s+(\d{1,2})',
    r'ребенок\s+(\d{1,2})',
    r'ей\s*(\d{1,2})',
    r'ему\s*(\d{1,2})',
    r'для\s*(\d{1,2})',             # для 5, для 8-летнего
    r'(\d{1,2})\s*-?\s*ти\b',       # 5-ти лет
]

def quick_extract_age(text):
    for p in _AGE_PATTERNS:
        m = re.search(p, text, re.IGNORECASE)
        if m:
            age = int(m.group(1))
            if 2 <= age <= 18:
                return age
    stripped = text.strip()
    if re.match(r'^\d{1,2}$', stripped):
        age = int(stripped)
        if 2 <= age <= 18:
            return age
    return None


# Возрастные слова-существительные: «летки», «трёхлетки», «пятилетке», «годик» и
# т.п. — это форма указания возраста, а НЕ интерес. Не должны попадать в значимые
# слова и не должны искаться как направление.
_WORDNUM = {
    'двух': 2, 'трёх': 3, 'трех': 3, 'четырёх': 4, 'четырех': 4, 'пяти': 5,
    'шести': 6, 'семи': 7, 'восьми': 8, 'девяти': 9, 'десяти': 10,
    'одиннадцати': 11, 'двенадцати': 12,
}
_AGE_NOUN_RE = re.compile(
    r'^(?:двух|трёх|трех|четырёх|четырех|пяти|шести|семи|восьми|девяти|десяти|'
    r'одиннадцати|двенадцати|полу)?(?:лет|летк\w*|летн\w*|годик\w*|годовал\w*)$'
)


def _is_age_word(w):
    return w in _AGE_WORDS or bool(_AGE_NOUN_RE.match(w))


def extract_all_ages(text):
    """Извлекает ВСЕ возрасты из текста (для нескольких детей)."""
    ages = set()

    # Первый проход: числа явно рядом с «лет», «год» и т.д.
    for m in re.finditer(
            r'(\d{1,2})\s*[-–]?\s*(лет|год|года|годик|летний|летняя|летнего|летней)',
            text, re.IGNORECASE):
        age = int(m.group(1))
        if 2 <= age <= 18:
            ages.add(age)

    # Второй проход: «дочери 7», «для 5», «ребёнку 10» и т.п.
    for p in [r'для\s+(\d{1,2})', r'дочери\s+(\d{1,2})', r'сыну\s+(\d{1,2})',
              r'ребёнку\s+(\d{1,2})', r'ребенку\s+(\d{1,2})', r'ей\s+(\d{1,2})',
              r'ему\s+(\d{1,2})', r'мальчик\w*\s+(\d{1,2})', r'девочк\w*\s+(\d{1,2})',
              r'дочк\w*\s+(\d{1,2})', r'сын\w*\s+(\d{1,2})',
              r'ребёнок\s+(\d{1,2})', r'ребенок\s+(\d{1,2})',
              r'подрост\w*\s+(\d{1,2})', r'дошкольник\w*\s+(\d{1,2})',
              r'школьник\w*\s+(\d{1,2})', r'малыш\w*\s+(\d{1,2})']:
        for m in re.finditer(p, text, re.IGNORECASE):
            age = int(m.group(1))
            if 2 <= age <= 18:
                ages.add(age)

    # Третий проход: если в тексте ≥2 числа в диапазоне 2-18 и слово «лет»/«ребёнок» есть —
    # подбираем ВСЕ числа как потенциальные возрасты
    if len(ages) < 2 and re.search(r'лет|год|ребён|детей|ребенок', text, re.IGNORECASE):
        all_nums = [int(m.group()) for m in re.finditer(r'\b(\d{1,2})\b', text)
                    if 2 <= int(m.group()) <= 18]
        if len(all_nums) >= 2:
            ages.update(all_nums)

    # Проход: словесные формы возраста — «трёхлетки», «пятилетний», «шестилетке»
    low = text.lower()
    for wn, a in _WORDNUM.items():
        if re.search(wn + r'\s*лет', low):
            if 2 <= a <= 18:
                ages.add(a)

    # Голое число если нет других
    if not ages:
        stripped = text.strip()
        if re.match(r'^\d{1,2}$', stripped):
            age = int(stripped)
            if 2 <= age <= 18:
                ages.add(age)

    return sorted(ages)


