# ═══════════════════════════════════════════════════════════════════════════════
# Слова, обозначающие возрастную группу, а НЕ направление. Раньше «подросток»
# в словаре раскрывался во все подростковые направления и затапливал конкретный
# интерес. Теперь такие слова трактуются как возрастной сигнал: исключаются из
# распознавания направлений и из backbone-слов, а возраст из них выводится, если
# в запросе нет явного числового возраста.
#
# Значение — репрезентативный возраст для одиночного age-фильтра (или None, если
# группа слишком широкая, например «школьник» 7-17 — тогда слово лишь подавляется
# как направление, но конкретный возраст не навязывается).
_AGE_PROXY_AGE = [
    ('дошкольник', 5), ('дошколь', 5), ('дошкольн', 5),
    ('первоклассник', 7), ('первоклашк', 7),
    ('подрост', 14), ('тинейдж', 14), ('тинэйдж', 14),
    ('малыш', 4), ('кроха', 3), ('карапуз', 3), ('крох', 3),
    ('старшеклассник', 15), ('старшекласс', 15),
    ('младшеклассник', 8), ('младшекласс', 8),
    ('школьник', None), ('школьн', None),  # широко — только подавляем как направление
]


def is_age_proxy(w):
    """Слово обозначает возрастную группу, а не направление."""
    return any(w.startswith(stem) for stem, _ in _AGE_PROXY_AGE)


# Русские глагольные приставки для снятия при матче направлений.
# Только аспектуальные «немного поделать X»: за-, на-, по-, с-. Шире не берём,
# чтобы не ловить ложно (напр. «про-думать»→«думать» — это другой смысл).
# 2-буквенные раньше 1-буквенной.
_VERB_PREFIXES = ('за', 'на', 'по', 'с')


def _strip_verb_prefix(w):
    """Возвращает слово без ведущей глагольной приставки (остаток >= 3 символов)."""
    for p in _VERB_PREFIXES:
        if w.startswith(p) and len(w) - len(p) >= 3:
            return w[len(p):]
    return w


def _levenshtein(a, b):
    m, n = len(a), len(b)
    d = list(range(n + 1))
    for i in range(1, m + 1):
        prev = d[0]
        d[0] = i
        for j in range(1, n + 1):
            cur = d[j]
            d[j] = min(d[j] + 1, d[j - 1] + 1, prev + (a[i - 1] != b[j - 1]))
            prev = cur
    return d[n]


def _fuzzy_typo_key(w, *maps):
    """
    Матч с опечаткой: сравниваем префикс слова (длиной с ключ) с ключом по
    Левенштейну. Ловит «ангийскаму»→«англ», «рисавать»→«рисовать» и т.п.,
    создавая keyword-якорь там, где вектор сам по себе ненадёжен.
    Порог жёсткий (1 для коротких ключей, 2 для длинных), чтобы не было ложных.
    """
    best, best_d = None, 99
    for m in maps:
        for key in m:
            if ' ' in key or len(key) < 4:
                continue
            L = len(key)
            if len(w) < L - 1:
                continue
            d = _levenshtein(w[:L], key)
            allow = 1 if L <= 5 else 2
            if d <= allow and d < best_d:
                best_d, best = d, key
    return best


def extract_age_proxy(text):
    """
    Возвращает репрезентативный возраст из слова-прокси (подросток→14,
    дошкольник→5 и т.п.) или None. Используется ТОЛЬКО когда явного числового
    возраста в запросе нет.
    """
    words = re.findall(r'[а-яёa-z\-]+', text.lower())
    for w in words:
        for stem, age in _AGE_PROXY_AGE:
            if age is not None and w.startswith(stem):
                return age
    return None


def detect_directions(text, synonym_map, category_map):
    """
    Находит ключевые слова направлений в тексте.
    Точный матч + матч по корню (мин 6 символов, разница длин <= 3).
    Стоп-слова и возрастные слова-прокси (подросток, дошкольник…) исключаются.
    """
    text_lower = text.lower()
    found = []

    words = re.findall(r'[а-яёa-z\-]+', text_lower)

    for w in words:
        if len(w) < 3 or w in _STOP_WORDS:
            continue
        # Возрастные слова-прокси НЕ являются направлением: «подросток» не должен
        # раскрываться во все подростковые направления и затапливать конкретный
        # запрос (напр. «подростку 16, хочу на вокал»). Возраст из них выводится
        # отдельно (extract_age_proxy).
        if is_age_proxy(w):
            continue
        # Возрастные слова (года, летки, трёхлетки…) — не направление; иначе
        # опечаточный матчер ловит «года»→«мода» и т.п.
        if _is_age_word(w):
            continue
        # Точный матч
        if w in category_map:
            found.append(w)
            continue
        if w in synonym_map:
            found.append(w)
            continue
        # Снятие русских глагольных приставок (по-, с-, за-, про-, на-, при-…):
        # «попеть»→«петь», «спеть»→«петь», «порисовать»→«рисовать»,
        # «затанцевать»→«танцевать». Принимаем только если остаток — РЕАЛЬНЫЙ ключ
        # словаря (иначе ложных срабатываний нет). Это общая морфология, не костыль.
        stripped = _strip_verb_prefix(w)
        if stripped and stripped != w:
            if stripped in category_map or stripped in synonym_map:
                found.append(stripped)
                continue
        # Матч по корню с адаптивным порогом:
        # - Ключи 3-4 буквы: совпадение первых 3 символов, разница длин <= 2
        # - Ключи 5-6 букв: совпадение первых 4 символов, разница длин <= 2
        # - Ключи 7+ букв: совпадение первых 6 символов, разница длин <= 3
        if len(w) >= 4:
            matched = False
            for key in category_map:
                if ' ' in key:
                    continue
                if len(key) < 3:
                    continue
                if len(key) <= 4:
                    min_prefix, max_diff = 3, 2
                elif len(key) <= 6:
                    min_prefix, max_diff = 4, 2
                else:
                    min_prefix, max_diff = 6, 3
                if (len(w) >= min_prefix
                        and abs(len(w) - len(key)) <= max_diff
                        and w[:min_prefix] == key[:min_prefix]):
                    if key not in found:
                        found.append(key)
                    matched = True
                    break
            if not matched:
                for key in synonym_map:
                    if ' ' in key:
                        continue
                    if len(key) < 3:
                        continue
                    if len(key) <= 4:
                        min_prefix, max_diff = 3, 2
                    elif len(key) <= 6:
                        min_prefix, max_diff = 4, 2
                    else:
                        min_prefix, max_diff = 6, 3
                    if (len(w) >= min_prefix
                            and abs(len(w) - len(key)) <= max_diff
                            and w[:min_prefix] == key[:min_prefix]):
                        if key not in found:
                            found.append(key)
                        matched = True
                        break
            # Опечаточный фолбэк (Левенштейн) — если префиксный матч не сработал
            if not matched:
                fk = _fuzzy_typo_key(w, category_map, synonym_map)
                if fk and fk not in found:
                    found.append(fk)

    # Многословные фразы
    for phrase in category_map:
        if ' ' in phrase and phrase in text_lower:
            if phrase not in found:
                found.append(phrase)
    for phrase in synonym_map:
        if ' ' in phrase and phrase in text_lower:
            if phrase not in found:
                found.append(phrase)

    return found


