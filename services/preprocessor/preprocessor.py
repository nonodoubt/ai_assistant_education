# Дни недели и слова доступности — не являются интересом/направлением.
# Префиксы ловят словоформы: «вторникам», «четвергам», «пятницам» и т.п.
_DAY_PREFIXES = (
    'понедельник', 'вторник', 'четверг', 'пятниц', 'суббот', 'воскресен',
    'среда', 'среду', 'среды', 'средам',
)
_AVAILABILITY_WORDS = {
    'свободна', 'свободен', 'свободно', 'свободны', 'свободные', 'свободное',
    'можем', 'может', 'можно', 'удобно', 'удобны', 'удобный', 'занят', 'занята',
    'заняты', 'ходить', 'ходим', 'посещать', 'посещаем', 'выходной', 'выходные',
    'подойдёт', 'подойдет', 'подойдут', 'подходит', 'подходящее', 'выбрать',
    'посоветуй', 'посоветуйте', 'посоветуете', 'подскажите', 'подскажи',
}


def _is_day_word(w):
    return any(w.startswith(p) for p in _DAY_PREFIXES)


def extract_significant_words(text):
    """
    Возвращает значимые слова запроса: НЕ стоп-слова, НЕ возраст, НЕ числа,
    НЕ вежливая вода, НЕ служебные слова (предлоги/союзы/частицы/местоимения).
    Это backbone-сигнал для контентного поиска (FTS + вектора), который работает
    даже если направление не распозналось по словарю синонимов.

    Принцип: словарь синонимов — лишь бустер. Содержательные слова пользователя
    всегда должны доходить до поиска по реальному тексту программ.
    """
    words = re.findall(r'[а-яёa-z\-]{3,}', text.lower())
    out = []
    for w in words:
        if (w in _STOP_WORDS or w in _AGE_WORDS or w in _FILLER_WORDS
                or w in _FUNCTION_WORDS or w in _AVAILABILITY_WORDS):
            continue
        if _is_age_word(w):
            continue
        if _is_day_word(w):
            continue
        if is_age_proxy(w):
            continue
        if re.match(r'^\d', w):
            continue
        if w not in out:
            out.append(w)
    return out


def query_has_content(text):
    """Есть ли в запросе хотя бы одно содержательное слово (не возраст/вода)."""
    if not text:
        return False
    return len(extract_significant_words(text)) > 0


