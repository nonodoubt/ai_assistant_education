DAY_STEMS = {
    "понедельник": ["понедельник"],
    "вторник":     ["вторник"],
    "среда":       ["сред"],
    "четверг":     ["четверг", "чтеверг"],   # в БД встречается опечатка «чтеверг»
    "пятница":     ["пятниц"],
    "суббота":     ["суббот"],
    "воскресенье": ["воскресен"],
}


def prog_on_days(p, days):
    sched = (p.get("schedule") or "").lower()
    for d in days:
        for stem in DAY_STEMS.get(d, [d]):
            if stem in sched:
                return True
    return False


def gt(ids=None, age=None, free=None, location=None, days=None):
    """Каноничные имена программ из группы ids, удовлетворяющие фильтрам."""
    if ids is None:
        ids = ALL_IDS
    names = []
    for pid in ids:
        p = ID2[pid]
        if age is not None:
            if p["age_min"] is not None and p["age_min"] > age:
                continue
            if p["age_max"] is not None and p["age_max"] < age:
                continue
        if free is not None and p["is_free"] != (1 if free else 0):
            continue
        if location is not None and (p.get("location_norm") or "").lower() != location.lower():
            continue
        if days and not prog_on_days(p, days):
            continue
        if p["name"] not in names:
            names.append(p["name"])
    return names


# ── Конструктор кейса ────────────────────────────────────────────────────────
def mk(cid, scenario, desc, user_input=None, turns=None, eval_turn=None,
       contains=None, not_contains=None, criteria="", eval_ret=False,
       ground_truth=None, problem=False, notes=""):
    if not_contains is None:
        not_contains = ["Произошла ошибка"]
    case = {
        "id": cid,
        "scenario": scenario,
        "scenario_desc": desc,
        "type": "multi" if turns else "single",
        "expected_contains": contains or [],
        "expected_not_contains": not_contains,
        "eval_criteria": criteria,
        "evaluate_retrieval": eval_ret,
        "ground_truth_programs": ground_truth or [],
        "problem_case": problem,
        "notes": notes,
    }
    if turns:
        case["turns"] = turns
        if eval_turn:
            case["eval_turn"] = eval_turn
    else:
        case["user_input"] = user_input
    # Валидация GT ⊆ каталог
    for n in case["ground_truth_programs"]:
        assert n in CATALOG, "GT не из каталога: %r (кейс %s)" % (n, cid)
    return case


def U(role, content):
    return {"role": role, "content": content}


def conv(*user_msgs):
    """Строит turns: user → __BOT_RESPONSE__ → user → ... ; eval_turn — последний."""
    turns = []
    for i, m in enumerate(user_msgs):
        turns.append(U("user", m))
        turns.append(U("assistant", "__BOT_RESPONSE__"))
    return turns, len(turns)


